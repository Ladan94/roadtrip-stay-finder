export type Point = { lat: number; lng: number };
export type RouteSample = Point & { seconds: number; meters: number };
export type Trip = {
  mode: 'demo' | 'live';
  postalCode: string;
  country: string;
  destination: string;
  direction: 'north' | 'south' | 'east' | 'west';
  driveHours: number;
  departureDate: string;
  departureTime: string;
  checkIn: string;
  checkOut: string;
  adults: number;
  children: number;
  budget: number;
  breakfast: boolean;
  minStars: number;
  minRating: number;
  maxDetour: number;
  stopWindow: number;
  breakEvery: number;
  breakMinutes: number;
};
export type Hotel = {
  id: string;
  name: string;
  address: string;
  location: Point;
  rating: number | null;
  reviews: number | null;
  stars: number | null;
  nightlyPrice: number | null;
  taxesIncluded: boolean | null;
  breakfast: 'included' | 'available' | 'unknown';
  detourMinutes: number | null;
  url: string;
  detourPath?: Point[];
  drivingMinutes?: number;
  photo?: string;
  photoAttribution?: string;
  priceStatus: 'sample' | 'unverified';
  source: 'demo' | 'google';
  score?: number;
};
export type Stop = {
  id: string;
  name: string;
  address: string;
  location: Point;
  category: string;
  rating: number | null;
  reviews: number | null;
  detourMinutes: number | null;
  arrival: string;
  hours: string[];
  openAtArrival: boolean | null;
  url: string;
};
export type Town = { name: string; location: Point; drivingMinutes: number };
export type Plan = {
  mode: 'demo' | 'live';
  exploratory: boolean;
  route: RouteSample[];
  originLabel: string;
  destinationLabel: string;
  distanceKm: number;
  drivingMinutes: number;
  breakMinutes: number;
  target: Point;
  targetMinutes: number;
  towns: Town[];
  hotels: Hotel[];
  stops: Stop[];
  warnings: string[];
  departure: string;
  attribution: string;
  bookingConnected: boolean;
};
